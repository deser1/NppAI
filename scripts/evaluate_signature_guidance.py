"""Compare free decoding with explicit task-provided Python signature prefixes.

The prefix is deterministic scaffolding, not an identifier generated by the model.
Reference answers are used only by scoring after both outputs have been captured.
"""
import argparse
import ast
import hashlib
import json
import keyword
from pathlib import Path
import re
import subprocess
import sys
import tempfile

sys.path.insert(0,str(Path(__file__).resolve().parent.parent))


def signature_prefix(task):
    if len(task)>4096 or task.count("(")!=1 or task.count(")")!=1:
        raise ValueError("requires one bounded plain signature")
    matches=list(re.finditer(r"\b([A-Za-z_][A-Za-z_0-9]*)\(([^()]*)\)",task))
    if len(matches)!=1:
        raise ValueError("task must contain exactly one explicit function signature")
    name, arguments=matches[0].groups()
    names=[arg.strip() for arg in arguments.split(",")] if arguments.strip() else []
    if keyword.iskeyword(name) or len(names)!=len(set(names)) or any(
        not re.fullmatch(r"[A-Za-z_][A-Za-z_0-9]*",arg) or keyword.iskeyword(arg) for arg in names):
        raise ValueError("only distinct plain Python parameter names are supported")
    return f"def {name}({', '.join(names)}):\n    "


def score(text, reference, function):
    try:
        tree=ast.parse(text)
        return {"syntax":True,
            "requested_function":any(isinstance(n,ast.FunctionDef) and n.name==function for n in tree.body),
            "reference_ast":ast.dump(tree)==ast.dump(ast.parse(reference))}
    except SyntaxError:
        return {"syntax":False,"requested_function":False,"reference_ast":False}


def run(model_path,dataset,output,native=None):
    from scripts.check_dense_runtime_parity import load_weights,torch_model
    from scripts.train_instruction_experiment import generate,prompt
    import torch
    torch.set_num_threads(2)
    w=load_weights(model_path)
    model=torch_model(w)
    records=json.loads(Path(dataset).read_text())
    cases=[]
    for record in records:
        prefix=signature_prefix(record["prompt"])
        raw=generate(model,record["prompt"],w["context"])
        guided=generate(model,record["prompt"],w["context"],prefix)
        case={"id":record["id"],"family":record["family"],
            "forced_prefix":prefix,"raw_output":raw,"guided_output":guided,
            "raw_score":score(raw,record["answer"],record["function"]),
            "guided_score":score(guided,record["answer"],record["function"])}
        if native:
            with tempfile.TemporaryDirectory() as directory:
                prefixfile=Path(directory)/"prefix.txt"
                target=Path(directory)/"output.txt"
                prefixfile.write_text(prefix,encoding="utf-8")
                result=subprocess.run([native,str(model_path),prompt(record["prompt"]),str(target),str(prefixfile)],capture_output=True,text=True,timeout=120)
                native_output=target.read_text(encoding="utf-8") if target.exists() else ""
                case.update(native_output=native_output,native_returncode=result.returncode,
                            native_stderr_tail=result.stderr[-1000:],
                            native_score=score(native_output,record["answer"],record["function"]))
        cases.append(case)
    modes=["raw","guided"]+(["native"] if native else [])
    report={"model_sha256":hashlib.sha256(Path(model_path).read_bytes()).hexdigest(),
        "dataset_sha256":hashlib.sha256(Path(dataset).read_bytes()).hexdigest(),
        "total":len(cases),"summary":{mode:{metric:sum(case[mode+"_score"][metric] for case in cases)
            for metric in ("syntax","requested_function","reference_ast")} for mode in modes},
        "cases":cases,"limitations":"Exposed v2 regression tasks. Guided signatures are forced from the task, not copied by the model. Static AST matching only; generated code is never executed. PyTorch FP32 and native INT8 may differ."}
    Path(output).write_text(json.dumps(report,indent=2)+"\n")
    print(json.dumps({k:v for k,v in report.items() if k!="cases"},indent=2))
    return report


if __name__=="__main__":
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--model",required=True)
    parser.add_argument("--dataset",required=True)
    parser.add_argument("--output",required=True)
    parser.add_argument("--native")
    args=parser.parse_args()
    run(args.model,args.dataset,args.output,args.native)
