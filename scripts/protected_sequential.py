def schedule(dataset):
    yield from prior.schedule(dataset, 'diverse')


def protocol(dataset, tasks):
    _, fingerprints = prior.inputs(dataset, tasks)
    return {'spec': SPEC, 'inputs': fingerprints, 'schedule': prior.schedule_evidence(dataset, 'diverse')}


def initial(weights, arm):
    model = curriculum.initial(weights)
    model.base.requires_grad_(False)
    if arm == 'frozen_sequential':
        from scripts.sequential_copy_model import SequentialCopyModel
        model = SequentialCopyModel(model)
    elif arm != 'frozen_soft':
        raise ValueError('unknown protected arm')
    return model


def sequential_loss(model, records, x, y):
    import torch
    from torch.nn import functional as F
    from scripts.aligned_name_copy import alignment
    from scripts.gated_copy_model import source_mask, aggregate
    mask = torch.stack([source_mask(x[i:i+1], r['prompt'])[0] for i, r in enumerate(records)])
    hidden, vocab, attention = model.components(x, mask)
    pointer = aggregate(attention, x)
    mixture = vocab.clone()
    starts, exits, labels = [], [], []
    for batch, record in enumerate(records):
        points = alignment(record)
        starts.append(attention[batch, points[0][0], points[0][1]])
        # Last training query predicts '('; source cursor points immediately after name.
        queries = points + [(points[-1][0] + 1, points[-1][1] + 1)]
        for index, (query, source) in enumerate(queries):
            if not bool(mask[batch, source]) or source >= query or int(y[batch, query]) < 0:
                raise ValueError('invalid sequential TRAIN cursor')
            if index < len(points) and int(x[batch, source]) != int(y[batch, query]):
                raise ValueError('unaligned sequential TRAIN cursor')
            probability = model.exit_probability(hidden[batch, query], hidden[batch, source]).squeeze()
            copy = pointer[batch, query] if index == 0 else F.one_hot(x[batch, source], 256).to(vocab.dtype)
            mixture[batch, query] = probability * vocab[batch, query] + (1 - probability) * copy
            exits.append(probability)
            labels.append(float(index == len(points)))
    nll = F.nll_loss(mixture.clamp_min(torch.finfo(mixture.dtype).tiny).log().reshape(-1, 256),
                     y.reshape(-1), ignore_index=-100)
    start = -torch.stack(starts).clamp_min(1e-30).log().mean()
    exit_loss = F.binary_cross_entropy(torch.stack(exits), torch.tensor(labels))
    loss = nll + start + 0.1 * exit_loss
    return loss, {'response_nll': float(nll.detach()), 'pointer_nll': float(start.detach()),
                  'gate_bce': float(exit_loss.detach())}


def train(weights, dataset, output, arm):
    import torch
    from scripts import gated_copy_model as soft
    from scripts import sequential_copy_model as sequential
    from scripts.training_repro import configure, state_digest
    configure(torch, quality.PROFILE)
    model = initial(weights, arm).train()
    frozen = state_digest(model.base)
    optimizer = torch.optim.AdamW((p for p in model.parameters() if p.requires_grad), lr=0.001,
                                 betas=(0.9, 0.999), eps=1e-8, weight_decay=0.01)
    output.mkdir(parents=True, exist_ok=True)
    trace = output / 'trace.jsonl'
    trace.write_bytes(quality.encoded({'step': 0, 'parameters': state_digest(model), 'base': frozen}))
    for step, (records, original) in enumerate(schedule(dataset)):
        samples = [base.sample(r) for r in records]
        x = torch.nn.utils.rnn.pad_sequence([s[0] for s in samples], batch_first=True)
        y = torch.nn.utils.rnn.pad_sequence([s[1] for s in samples], batch_first=True, padding_value=-100)
        loss, parts = (sequential_loss(model, records, x, y) if arm == 'frozen_sequential' else
                       curriculum.losses(model, records, x, y, True))
        if not math.isfinite(float(loss.detach())):
            raise ValueError('nonfinite protected loss')
        optimizer.zero_grad(set_to_none=True)
        loss.backward()
        torch.nn.utils.clip_grad_norm_(model.parameters(), 1.0, error_if_nonfinite=True)
        optimizer.step()
        if (any(p.grad is not None or p.requires_grad for p in model.base.parameters()) or
                state_digest(model.base) != frozen or any(not torch.isfinite(p).all() for p in model.parameters())):
            raise ValueError('frozen base/finite parameter invariant failed')
        with trace.open('ab') as stream:
            stream.write(quality.encoded({'step': step + 1, 'base': frozen, 'parameters': state_digest(model),
                'batch_sha256': quality.digest(quality.encoded({'records': records, 'original': original})),
                'loss_hex': float(loss.detach()).hex(), 'losses': parts}))
        if step % 128 == 0 or step == STEPS - 1:
            print(json.dumps({'arm': arm, 'step': step + 1, **parts}), flush=True)
    format_module = sequential if arm == 'frozen_sequential' else soft
    checkpoint = output / 'experimental.nppaicopy'
    format_module.export_bundle(model.eval(), checkpoint, 'sha256:' + quality.CHECKPOINTS['both64'])
    loaded, _ = format_module.load_bundle(checkpoint)
    loaded.base.requires_grad_(False)
    if state_digest(model) != state_digest(loaded) or state_digest(loaded.base) != frozen:
        raise ValueError('protected roundtrip differs')
    return loaded, {'checkpoint_sha256': quality.digest(checkpoint.read_bytes()),
                    'trace_sha256': quality.digest(trace.read_bytes()), 'base_state': frozen,
                    'roundtrip_equal': True, 'base_unchanged': True}


def evaluate(model, groups, arm):
    if arm == 'frozen_soft':
        return prior.evaluate(model, groups)
    from scripts.sequential_copy_model import generate
    result = {}
    for group, rows in groups.items():
        result[group] = []
        for i, row in enumerate(rows):
            output, events, output_bytes = generate(model, row['prompt'], with_events=True)
            result[group].append({'index': i, 'id': row['id'], 'output': output,
                'metrics': base.score(row, output), 'name_prefix': output.startswith('def ' + row['function'] + '('),
                'events': events, 'output_bytes': output_bytes})
    return result


def audit_events(case, row):
    frame = ('[USER]: ' + row['prompt'] + '\n[AI]:\n').encode()
    left, right = len(b'[USER]: '), len(b'[USER]: ' + row['prompt'].encode())
    events = case['events']
    output_bytes = case['output_bytes']
    if (any(type(b) != int or not 0 <= b <= 255 for b in output_bytes) or
            bytes(output_bytes).decode('utf-8', errors='replace') != case['output']):
        raise ValueError('sequential raw output bytes differ')
    # Outputs with invalid UTF-8 are decoded with replacement; raw event bytes still audited against source.
    previous = None
    for i, event in enumerate(events):
        query, cursor = event['response_query'], event['cursor']
        if not 4 <= query < 160 or (i == 0 and query != 4) or not 0 <= event['base_byte'] < 256:
            raise ValueError('sequential event timing differs')
        if previous is not None and (previous['kind'] != 'copy' or query != previous['response_query'] + 1 or
                                     cursor != previous['cursor'] + 1):
            raise ValueError('sequential cursor transition differs')
        offset = max(0, len(frame) + query - 256)
        valid = left <= cursor < right and cursor >= offset and frame[cursor] != 0
        if event['kind'] == 'boundary':
            if valid or event['chosen'] != event['base_byte']:
                raise ValueError('sequential source boundary differs')
        else:
            p = event['exit_probability']
            if not valid or event['source_byte'] != frame[cursor] or not math.isfinite(p) or not 0 <= p <= 1:
                raise ValueError('sequential prompt source/probability differs')
            exit_name = p >= 0.5
            if (event['kind'] != ('exit' if exit_name else 'copy') or
                    event['chosen'] != (event['base_byte'] if exit_name else frame[cursor])):
                raise ValueError('sequential exit decision differs')
        if event['chosen'] != (output_bytes[query] if query < len(output_bytes) else 0):
            raise ValueError('sequential emitted byte differs')
        previous = event
    if events and not case['output'].startswith('def '):
        raise ValueError('sequential autonomous trigger differs')


def audit_trace(raw, dataset, arm, identity):
    if quality.digest(raw) != identity['trace_sha256']:
        raise ValueError('protected trace hash differs')
    rows = [json.loads(line) for line in raw.splitlines()]
    if len(rows) != STEPS + 1 or [r['step'] for r in rows] != list(range(STEPS + 1)):
        raise ValueError('protected trace steps differ')
    if any(r['base'] != identity['base_state'] or not re.fullmatch('[0-9a-f]{64}', r['parameters']) for r in rows):
        raise ValueError('protected frozen base differs')
    for (records, original), row in zip(schedule(dataset), rows[1:]):
        if row['batch_sha256'] != quality.digest(quality.encoded({'records': records, 'original': original})):
            raise ValueError('protected training exposure differs')
        parts = row['losses']
        if set(parts) != {'response_nll', 'pointer_nll', 'gate_bce'} or any(
                not math.isfinite(v) or v < 0 for v in parts.values()):
            raise ValueError('protected loss components differ')
        expected = parts['response_nll'] + parts['pointer_nll'] + 0.1 * parts['gate_bce']
        loss = float.fromhex(row['loss_hex'])
        if not math.isfinite(loss) or not math.isclose(loss, expected, rel_tol=1e-6, abs_tol=1e-5):
            raise ValueError('protected loss total differs')
    return rows


def audit(report, dataset, tasks):
    raw = (ROOT / 'evaluation/protected-sequential-v1.json').read_bytes()
    groups, fingerprints = prior.inputs(dataset, tasks)
    if (json.loads(raw) != protocol(dataset, tasks) or report['protocol_sha256'] != quality.digest(raw) or
            report['spec'] != SPEC or report['inputs'] != fingerprints or report['promotion'] is not False or
            set(report['arms']) != set(ARMS)):
        raise ValueError('protected protocol provenance differs')
    frozen = set()
    for arm, result in report['arms'].items():
        identity = result['identity']
        frozen.add(identity['base_state'])
        if (any(identity[k] is not True for k in ('roundtrip_equal', 'base_unchanged')) or
                result['same_host_repeat_equal'] is not True or result['parameters_unchanged_by_evaluation'] is not True or
                any(not re.fullmatch('[0-9a-f]{64}', identity[k]) for k in
                    ('checkpoint_sha256', 'trace_sha256', 'base_state'))):
            raise ValueError('protected training identity differs')
        for stage in ('before', 'after'):
            if (result[stage + '_summary'] != prior.audit_views(result[stage], groups) or
                    result[stage + '_prefix_summary'] != prior.prefix_summary(result[stage])):
                raise ValueError('protected summary differs')
            if arm == 'frozen_sequential':
                for group, cases in result[stage].items():
                    for case, row in zip(cases, groups[group]):
                        audit_events(case, row)
        if result['retention'] != base.retention(result['before'], result['after']):
            raise ValueError('protected exact retention differs')
        f = result['functional']
        if (f['manifest_sha256'] != fingerprints['tasks_sha256'] or set(f['models']) != {'copy'} or
                not re.fullmatch('sha256:[0-9a-f]{64}', f['image'])):
            raise ValueError('protected functional provenance differs')
        measured = f['models']['copy']
        expected = json.loads(tasks.read_bytes())
        if measured['tasks'] != len(expected) or len(measured['cases']) != len(expected):
            raise ValueError('protected functional count differs')
        for case, task in zip(measured['cases'], expected):
            if (any(case[k] != value for k, value in task.items()) or
                    case['suite_sha256'] != fingerprints['suites'][task['task_id']] or
                    case['category'] not in ('empty', 'syntax_failure', 'functional_failure', 'passed')):
                raise ValueError('protected functional case differs')
        if measured['passed'] != sum(c['category'] == 'passed' for c in measured['cases']):
            raise ValueError('protected functional pass count differs')
    if len(frozen) != 1:
        raise ValueError('paired bases differ')
    return True


def functional(model, tasks, image, arm):
    from scripts.train_gated_copy import functional_probes
    if arm == 'frozen_soft':
        return functional_probes({'copy': model}, tasks, image)
    from scripts.sequential_copy_model import generate
    import sandbox_validate
    items = []
    for task in json.loads(tasks.read_bytes()):
        cases, suite = sandbox_validate.load_cases(Path(task['cases_file']))
        source = generate(model, task['prompt'])
        category, detail = 'empty', 'Empty/whitespace output'
        if source.strip():
            status, detail = sandbox_validate.validate(source, 'syntax', cases, image)
            category = 'syntax_failure'
            if status == 0:
                status, detail = sandbox_validate.validate(source, 'tests', cases, image)
                category = 'passed' if status == 0 else 'functional_failure'
            if status not in (0, 1):
                raise RuntimeError('validation infrastructure: ' + detail[:512])
        items.append({**task, 'source': source, 'suite_sha256': suite,
                      'category': category, 'diagnostics': detail[:4096]})
    return {'manifest_sha256': quality.digest(tasks.read_bytes()), 'image': image,
            'models': {'copy': {'tasks':len(items), 'passed':sum(c['category']=='passed' for c in items), 'cases':items}},
            'limits':'Six previously exposed regression probes, not fresh independent task accuracy.'}


def run(archive, dataset, tasks, output, image):
    import torch
    from scripts.check_dense_runtime_parity import load_weights
    from scripts.training_repro import configure, provenance, state_digest
    raw = (ROOT / 'evaluation/protected-sequential-v1.json').read_bytes()
    if json.loads(raw) != protocol(dataset, tasks):
        raise ValueError('predeclared protocol differs')
    weights = load_weights(quality.checkpoints(archive, output / 'source')['both64'])
    configure(torch, quality.PROFILE)
    groups, fingerprints = prior.inputs(dataset, tasks)
    report = {'protocol_sha256': quality.digest(raw), 'spec': SPEC, 'inputs': fingerprints,
              'runtime': provenance(torch, quality.PROFILE), 'arms': {}, 'promotion': False}
    for arm in ARMS:
        before = evaluate(initial(weights, arm).eval(), groups, arm)
        model, identity = train(weights, dataset, output / arm / '0', arm)
        _, repeated = train(weights, dataset, output / arm / '1', arm)
        if identity != repeated or any((output / arm / '0' / name).read_bytes() !=
                (output / arm / '1' / name).read_bytes() for name in ('trace.jsonl', 'experimental.nppaicopy')):
            raise ValueError('protected same-host repeat differs')
        audit_trace((output / arm / '0/trace.jsonl').read_bytes(), dataset, arm, identity)
        state = state_digest(model)
        after = evaluate(model, groups, arm)
        functional_result = functional(model, tasks, image, arm)
        result = {'before': before, 'after': after, 'identity': identity,
                  'same_host_repeat_equal': True, 'retention': base.retention(before, after),
                  'functional': functional_result, 'parameters_unchanged_by_evaluation': state == state_digest(model)}
        if not result['parameters_unchanged_by_evaluation']:
            raise ValueError('evaluation changed protected model')
        for stage in ('before', 'after'):
            result[stage + '_summary'] = prior.audit_views(result[stage], groups)
            result[stage + '_prefix_summary'] = prior.prefix_summary(result[stage])
        report['arms'][arm] = result
        (output / 'report.json').write_bytes(quality.encoded(report))
        print(json.dumps({'arm': arm, 'summary': result['after_summary'],
                          'functional_passed': functional_result['models']['copy']['passed'],
                          'retention': result['retention']['train/original']}), flush=True)
    audit(report, dataset, tasks)
    return report


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
